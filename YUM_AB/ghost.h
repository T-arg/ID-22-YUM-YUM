// one strip, mirrored (left <-> right), same result as sprites.drawPlusMask() would give for the mirrored picture
static void drawStripMirrored(int16_t x, int16_t y, byte s)
{
  if (x <= -18 || x >= 128 || y <= -8 || y >= 64) return;
  const unsigned char *d = pageSheet + 2 + s * 36;
  uint8_t *buf = arduboy.getBuffer();
  int8_t r = y >> 3;                                       // the screen row (of 8 px) the strip starts in, the rest lands in the next one
  uint8_t mul = 1 << (y & 7);
  for (byte i = 0; i < 18; i++)
  {
    int16_t sx = x + i;
    if (sx < 0 || sx > 127) continue;
    uint16_t sp = pgm_read_byte(d + 34 - 2 * i) * mul;      // column 17 - i
    uint16_t mk = pgm_read_byte(d + 35 - 2 * i) * mul;
    if (r >= 0 && r < 8)
    {
      uint8_t *q = buf + r * 128 + sx;
      *q = (*q & ~(uint8_t)mk) | (uint8_t)sp;
    }
    if (r >= -1 && r < 7)
    {
      uint8_t *q = buf + (r + 1) * 128 + sx;
      *q = (*q & ~(uint8_t)(mk >> 8)) | (uint8_t)(sp >> 8);
    }
  }
}

// draws frame f (3 strips) with its top left corner at x, y
static void drawStrips(int16_t x, int16_t y, byte f)
{
  const unsigned char *p = pageIdx + f * 3;
  for (byte i = 0; i < 3; i++, y += 8)
  {
    byte s = pgm_read_byte(p++);
    if (s == 255) continue;
    if (s & 0x80) drawStripMirrored(x, y, s & 0x7f);
    else sprites.drawPlusMask(x, y, pageSheet, s);
  }
}

